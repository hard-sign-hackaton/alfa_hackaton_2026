"""Read the shared news module without copying articles into the company database."""
import os

from contracts import NewsEvent
from database import DatabaseError
from retrieval import RetrievedSource, timestamp


class NewsReader:
    def __init__(self, url, *, mode='lexical', profile_id=None, embeddings=None):
        from app.shared.db.session import get_session_factory
        from app.modules.news.repositories import NewsRepository, NewsEmbeddingRepository
        if mode not in ('lexical', 'semantic'):
            raise ValueError('NEWS_SEARCH_MODE must be lexical or semantic')
        self.articles = NewsRepository(get_session_factory(url))
        self.vectors = NewsEmbeddingRepository(get_session_factory(url))
        self.mode, self.profile_id, self.embeddings = mode, profile_id, embeddings
        self.metadata = {}

    @classmethod
    def from_env(cls):
        url = os.environ.get('NEWS_DATABASE_URL')
        return cls(url, mode=os.environ.get('NEWS_SEARCH_MODE', 'lexical'),
                   profile_id=os.environ.get('NEWS_EMBEDDING_PROFILE') or None) if url else None

    @staticmethod
    def _read(operation):
        from sqlalchemy.exc import SQLAlchemyError
        try:
            return operation()
        except SQLAlchemyError:
            raise DatabaseError('News database read failed') from None

    def resolve(self, news_id, legacy_url=None, *, as_of=None):
        article = self._read(lambda: self.articles.get_article(news_id, as_of=as_of))
        if article is None and legacy_url:
            article = self._read(lambda: self.articles.get_by_url(legacy_url, as_of=as_of))
        if article is None:
            raise ValueError('Publication missing from news module or not yet published')
        return article.id

    def get_news(self, news_id, *, as_of):
        article = self._read(lambda: self.articles.get_article(news_id, as_of=timestamp(as_of)))
        if article is None:
            raise ValueError('Publication missing from news module or not yet published')
        self.metadata[article.id] = {name: article.model_dump(mode='json')[name] for name in
            ('publisher', 'source_id', 'collected_at', 'date_provenance', 'extraction_method', 'limitations')}
        return NewsEvent.model_validate(article.ai_event())

    def _semantic(self):
        from app.modules.news.services.search import NewsSearchService
        from app.modules.news.services.embedding import NewsEmbeddingService
        if self.embeddings is None:
            profiles = self._read(self.vectors.list_profiles)
            profile = next((p for p in profiles if p['id'] == self.profile_id), None) if self.profile_id else (profiles[0] if len(profiles) == 1 else None)
            if profile is None:
                raise DatabaseError('Select an existing NEWS_EMBEDDING_PROFILE; embeddings are not generated by the agent')
            try:
                from app.shared.embeddings.e5 import E5Provider
                embeddings = NewsEmbeddingService(self.vectors, E5Provider(revision=profile['revision']))
                if embeddings.profile != profile:
                    raise DatabaseError('Stored news embedding profile is incompatible')
                self.embeddings = embeddings
            except (ImportError, OSError, RuntimeError):
                raise DatabaseError('Semantic model unavailable; use the semantic agent image or NEWS_SEARCH_MODE=lexical') from None
        return NewsSearchService(self.vectors, self.embeddings)

    def search_news(self, query, *, as_of, exclude_id, limit=3):
        if self.mode == 'semantic':
            results = self._read(lambda: self._semantic().search(query, limit, as_of=timestamp(as_of), exclude_id=exclude_id))
        else:
            results = self._read(lambda: self.articles.search_text(query, limit, as_of=timestamp(as_of), exclude_id=exclude_id))
        return [RetrievedSource(source_id='news:' + row['id'], kind='news', title=row['title'][:500],
                    text=(row['title'] + '\n' + row['text'])[:6000], published_at=row['published_at'],
                    locator=row['url'], url=row['url'], publisher=row['publisher'], collected_at=row['collected_at']) for row in results]
