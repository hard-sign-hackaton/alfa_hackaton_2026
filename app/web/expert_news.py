"""Fictional publications grounded in the selected dataset profiles, without assessment labels."""


def company_publications(company):
    company_id, code, activity = company['id'], company['okved'], company['industry']
    identity = f"Компания {company_id}. Основной ОКВЭД: {code} — {activity}. Регистрация: {company.get('region') or 'не указана'}."
    return [
        {'case': 'operations_restriction', 'target_company_id': company_id,
         'title': f'ТЕСТ: {company_id}: основные операции приостановлены на десять рабочих дней',
         'text': identity + ' В вымышленном событии компания получила вступившее в силу предписание: '
                 f'с завтрашнего дня на десять рабочих дней приостановить деятельность «{activity}» '
                 f'по ОКВЭД {code}, включая приём новых заказов и исполнение действующих. '
                 f'В перечне адресатов прямо указано юридическое лицо {company_id}. Ограничение распространяется '
                 'на основную деятельность компании, а не на экспериментальный продукт или отдельного контрагента. '
                 'Возобновление операций возможно после устранения нарушений и повторной проверки. '
                 'Размер потерь не сообщается. Это вымышленная публикация экспертного сценария.'},
        {'case': 'service_tariffs', 'target_company_id': company_id,
         'title': f'ТЕСТ: сервисный партнёр {company_id} повышает тарифы по действующему договору',
         'text': identity + ' В вымышленной публикации сервисный оператор уведомил: '
                 f'через сорок пять дней тариф на сопровождение расчётов и обмен документами по договору с {company_id} '
                 'увеличится на восемь процентов: стоимость годового пакета вырастет с 300 до 324 миллионов рублей. Уведомление содержит обе суммы и дату начала нового тарифа. Оператор обеспечивает сопровождение операционных договоров и обмен документами для сделок '
                 f'компании в сфере «{activity}»; повышение касается только этой услуги, а не всей себестоимости. '
                 f'Договор с компанией {company_id} действует, уведомление о новой цене направлено ей персонально. '
                 'Основная деятельность, поставки и платежи продолжаются без остановки. Компания может '
                 'согласовать прежний тариф или выбрать другого оператора до начала нового периода. '
                 'Доля услуги в совокупных расходах и возможность перенести дополнительные затраты в цены клиентам неизвестны; совокупный финансовый '
                 'эффект для компании не рассчитан. Это вымышленная публикация экспертного сценария.'},
    ]


def scenario_publications(companies):
    # Queue both events for one company together so both kinds finish early in a run.
    pairs = [company_publications(company) for company in companies]
    entries = [article for pair in pairs for article in pair]
    entries.append({'case': 'control', 'title': 'ТЕСТ: отраслевой музей обновил расписание бесплатных экскурсий',
                    'text': 'Вымышленная культурная новость: музей обновил расписание бесплатных экскурсий '
                            'для школьников. Новость не содержит решений о деятельности компаний, '
                            'контрактах, налогах, ставках или обязательных требованиях. '
                            'Это вымышленная публикация экспертного сценария.'})
    return entries
